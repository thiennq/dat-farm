# Helper function to create a spritesheet from frames
def create_spritesheet(frames, frame_width, frame_height, cols, rows, output_path):
    sheet = Image.new('RGBA', (frame_width * cols, frame_height * rows), (0, 0, 0, 0))
    for r in range(rows):
        for c in range(cols):
            idx = r * cols + c
            if idx < len(frames):
                frame_img = draw_frame(frames[idx], frame_width, frame_height)
                sheet.paste(frame_img, (c * frame_width, r * frame_height))
    sheet.save(output_path)
    print(f"Saved spritesheet to {output_path}")

def draw_frame(grid, width, height):
    img = Image.new('RGBA', (width, height), (0, 0, 0, 0))
    pixels = img.load()
    for y in range(len(grid)):
        row = grid[y]
        for x in range(len(row)):
            char = row[x]
            if char in COLOR_MAP:
                pixels[x, y] = COLOR_MAP[char]
    return img

