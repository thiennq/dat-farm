# Helper to flip chicken frames horizontally
def flip_frame(frame):
    flipped = []
    for row in frame:
        # We need to reverse the characters, but also handle asymmetrical character pixels:
        # e.g., beak is on the left in left-view (owwbw), so reversing makes it right-view (wbwwo)
        # That is naturally correct! Let's just reverse the string.
        flipped.append(row[::-1])
    return flipped

