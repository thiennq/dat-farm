# Create brown chicken frames by mapping white colors to brown
def make_brown(frames):
    brown_frames = []
    for frame in frames:
        b_frame = []
        for row in frame:
            b_row = row.replace('w', 'y').replace('g', 'u')
            b_frame.append(b_row)
        brown_frames.append(b_frame)
    return brown_frames

